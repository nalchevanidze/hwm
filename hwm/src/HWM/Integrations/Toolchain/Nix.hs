syncNixFile :: ConfigT Status
syncNixFile = do
  Config {..} <- asks config
  ops <- asks options
  benv <- getBuildEnvironment Nothing
  benvs <- filter buildNix <$> getBuildEnvironments
  syncFile (optionsNix ops) (deriveFlakeNix (cfgName, benv) (map (cfgName,) benvs))

genName :: (Text, Text) -> Text
genName (name, subName) = toCamelCase (name <> T.toTitle subName <> "WorkspacePackages")

renderName :: Context -> Text
renderName (name, BuildEnvironment {..}) = genName (name, format buildName)

pkgsNixName :: Context -> Text
pkgsNixName ctx = "pkgs." <> renderName ctx

type Context = (Name, BuildEnvironment)

generateOverlay :: Context -> [Context] -> [Text]
generateOverlay static benvs =
  ["haskellOverlay = final: prev: {"]
    <> concatMap rendergOverlayItem benvs
    <> rendergOverlayStatic static
    <> ["};"]

stripExecutables :: (Semigroup a, IsString a) => a -> a
stripExecutables x = "prev.haskell.lib.justStaticExecutables (" <> x <> ")"

artifactEngine :: [Text]
artifactEngine =
  [ "# --- THE RELEASE ARTIFACT ENGINE ---",
    "# This function decides HOW to package the binary based on the OS running the build.",
    "mkReleaseArtifact = pkgName: basePkg: staticPkg:",
    "  if pkgs.stdenv.hostPlatform.isLinux then",
    "    # LINUX: Return the fully static (musl), zero-dependency executable",
    "    staticPkg",
    "  else if pkgs.stdenv.hostPlatform.isDarwin then",
    "    # MACOS: We \"Bundle\" the dynamic dependencies since strict static is hard on Mac.",
    "    pkgs.runCommand \"${pkgName}-macos-bundle\" {",
    "      nativeBuildInputs = [ pkgs.macdylibbundler pkgs.darwin.autoSignDarwinBinariesHook ];",
    "    } ''",
    "      mkdir -p $out/bin",
    "",
    "      # 1. Copy the fast, dynamically linked binary (stripping docs/libs first)",
    "      cp ${pkgs.haskell.lib.justStaticExecutables basePkg}/bin/${pkgName} $out/bin/${pkgName}",
    "      chmod 755 $out/bin/${pkgName}",
    "",
    "      # 2. Run dylibbundler to pull all Nix store .dylibs into the local folder",
    "      dylibbundler -b --no-codesign -x $out/bin/${pkgName} -d $out/bin -p '@executable_path'",
    "",
    "      # 3. Re-sign the binary so Apple Silicon (M1/M2/M3) allows it to run natively",
    "      signDarwinBinariesInAllOutputs",
    "    ''",
    "  else",
    "    # Fallback for unexpected systems",
    "    basePkg;"
  ]

rendergOverlayStatic :: Context -> [Text]
rendergOverlayStatic (projectName, BuildEnvironment {..}) =
  [ "  " <> genName (projectName, "static") <> " = prev.pkgsStatic.haskell.packages." <> formatNixGhc buildGHC <> ".extend (hfinal: hprev: {"
  ]
    <> map (renderPackageDef (stripExecutables . renderPackageBody)) buildPkgs
    <> ["  });"]

rendergOverlayItem :: Context -> [Text]
rendergOverlayItem ctx@(_, BuildEnvironment {..}) =
  [ "  " <> renderName ctx <> " = prev.haskell.packages." <> formatNixGhc buildGHC <> ".extend (hfinal: hprev: {"
  ]
    <> map (renderPackageDef renderPackageBody) buildPkgs
    <> ["  });"]

renderPackageDef :: (Pkg -> Text) -> Pkg -> Text
renderPackageDef body pkg = "    " <> format (pkgName pkg) <> " =  " <> body pkg <> ";"

renderPackageBody :: Pkg -> Text
renderPackageBody pkg = " hfinal.callCabal2nix \"" <> format (pkgName pkg) <> "\" ./" <> format (pkgDirPath pkg) <> " {}"

deriveFlakeNix :: Context -> [Context] -> Text
deriveFlakeNix ctx@(projectName, benv) ctxs =
  T.unlines
    $ braces
      ( [ "description = \"A Haskell " <> projectName <> " workspace generated by HWM(Haskell Workspace Manager)\";",
          "inputs = {",
          "  nixpkgs.url = \"github:NixOS/nixpkgs/" <> eraNixpkgs (selectEra (buildGHC benv)) <> "\";",
          "};",
          "outputs = { self, nixpkgs }:"
        ]
          <> letBlock
            ( [ "supportedSystems = [ " <> T.intercalate " " (map show systems) <> " ];",
                "forAllSystems = nixpkgs.lib.genAttrs supportedSystems;"
              ]
                <> generateOverlay ctx ctxs
            )
            ( forAllSystems "packages" (generatePublicPackages projectName benv (map snd ctxs))
                <> forAllSystems "devShells" (generateDevShell True ctx <> concatMap (generateDevShell False) ctxs)
                <> ["checks = forAllSystems (system: self.packages.${system});"]
            )
            False
      )

systems :: [Text]
systems =
  [ "x86_64-linux",
    "aarch64-linux",
    "x86_64-darwin",
    "aarch64-darwin"
  ]

braces :: [Text] -> [Text]
braces body =
  ["{"] <> map ("  " <>) body <> ["}"]

-- Notice the new signature: we pass the default environment, then all environments
generatePublicPackages :: Name -> BuildEnvironment -> [BuildEnvironment] -> [Text]
generatePublicPackages projectName defaultEnv allEnvs =
  defaultPkgAlias <> basePkgs <> matrixPkgs
  where
    defaultOverlay = renderName (projectName, defaultEnv)
    defaultPkgAlias =
      let defaultPkg = filter ((projectName ==) . format . pkgName) (buildPkgs defaultEnv)
       in map (\pkg -> "default = pkgs." <> defaultOverlay <> "." <> format (pkgName pkg) <> ";") defaultPkg
    basePkgs =
      map (\pkg -> format (pkgName pkg) <> " = pkgs." <> defaultOverlay <> "." <> format (pkgName pkg) <> ";") (buildPkgs defaultEnv)
    matrixPkgs = concatMap (generateMatrixPkgs . (projectName,)) allEnvs <> generateStaticPkgs (projectName, defaultEnv)

individualPkg :: Text -> Text -> Pkg -> Text
individualPkg overlay envName pkg = format (pkgName pkg) <> "-" <> envName <> " = pkgs." <> overlay <> "." <> format (pkgName pkg) <> ";"

generateStaticPkgs :: Context -> [Text]
generateStaticPkgs (projectname, env) = map (individualPkg (genName (projectname, "static")) "static") (buildPkgs env)

generateMatrixPkgs :: (Name, BuildEnvironment) -> [Text]
generateMatrixPkgs (projectName, env) =
  let overlay = renderName (projectName, env)
      envRaw = format (buildName env)
      envName = toCamelCase envRaw
      pathList = map (\pkg -> "    pkgs." <> overlay <> "." <> format (pkgName pkg)) (buildPkgs env)
   in map (individualPkg overlay envName) (buildPkgs env)
        <> [ "env-" <> envName <> "-all = pkgs.symlinkJoin {",
             "  name = \"" <> envRaw <> "-workspace\";",
             "  paths = [ "
           ]
        <> pathList
        <> [ " ];",
             "};"
           ]

generateDevShell :: Bool -> Context -> [Text]
generateDevShell _ (_, BuildEnvironment {buildPkgs = []}) = [] -- Handle empty workspace
generateDevShell isDefault (projectName, benv@BuildEnvironment {..}) =
  [ name <> " = " <> pkgsNixName (projectName, benv) <> ".shellFor {",
    "  packages = p: [ " <> renderPackageList buildPkgs <> " ];",
    "  buildInputs = with " <> pkgsNixName (projectName, benv) <> "; ["
  ]
    <> map ("    " <>) libs
    <> [ "  ];",
         "};"
       ]
  where
    name = if isDefault then "default" else toCamelCase (format buildName)
    libs = ["cabal-install", "hlint"] <> ["stack" | buildStack] <> ["haskell-language-server" | buildHie]
    renderPackageList = T.intercalate " " . map (\pkg -> "p." <> format (pkgName pkg))

letBlock :: [Text] -> [Text] -> Bool -> [Text]
letBlock h body end =
  ["  let"]
    <> map ("    " <>) h
    <> [ "  in",
         "  {"
       ]
    <> map ("    " <>) body
    <> if end then ["  });"] else ["  };"]

forAllSystems :: Text -> [Text] -> [Text]
forAllSystems system body =
  [system <> " = forAllSystems (system:"]
    <> letBlock
      ["pkgs = import nixpkgs { inherit system; overlays = [ haskellOverlay ]; };"]
      body
      True
