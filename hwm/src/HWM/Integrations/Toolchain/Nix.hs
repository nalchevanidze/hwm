module HWM.Integrations.Toolchain.Nix (syncNixFile) where

import qualified Data.Text as T
import HWM.Core.Common (Name)
import HWM.Core.Formatting (Status, format, toCamelCase)
import HWM.Core.Options (Options (..))
import HWM.Core.Pkg (Pkg (..))
import HWM.Core.Version (Era (eraNixpkgs), formatNixGhc, selectEra)
import HWM.Domain.Config (Config (Config, cfgName))
import HWM.Domain.ConfigT (ConfigT, Env (..))
import HWM.Domain.Environments (BuildEnvironment (..), getBuildEnvironment, getBuildEnvironments)
import HWM.Runtime.Files (syncFile)
import Relude

syncNixFile :: ConfigT Status
syncNixFile = do
  Config {..} <- asks config
  ops <- asks options
  -- TODO: fix later to avoid redundant calls to getBuildEnvironment
  benv <- getBuildEnvironment Nothing
  benvs <- reverse <$> getBuildEnvironments
  syncFile (optionsNix ops) (deriveFlakeNix (cfgName, benv) (map (cfgName,) benvs))

renderName :: Context -> Text
renderName (name, BuildEnvironment {..}) = toCamelCase name <> T.toTitle (format buildName) <> "WorkspacePackages"

pkgsNixName :: Context -> Text
pkgsNixName ctx = "pkgs." <> renderName ctx

type Context = (Name, BuildEnvironment)

generateOverlay :: [Context] -> [Text]
generateOverlay benvs =
  ["haskellOverlay = final: prev: {"]
    <> concatMap rendergOverlayItem benvs
    <> ["};"]

rendergOverlayItem :: Context -> [Text]
rendergOverlayItem ctx@(_, BuildEnvironment {..}) =
  [ "  " <> renderName ctx <> " = prev.haskell.packages." <> formatNixGhc buildGHC <> ".extend (hfinal: hprev: {"
  ]
    <> map renderPackage buildPkgs
    <> ["  });"]

renderPackage :: Pkg -> Text
renderPackage pkg = "      " <> format (pkgName pkg) <> " = hfinal.callCabal2nix \"" <> format (pkgName pkg) <> "\" ./" <> format (pkgDirPath pkg) <> " {};"

deriveFlakeNix :: Context -> [Context] -> Text
deriveFlakeNix ctx@(projectName, benv) ctxs =
  T.unlines
    $ braces
      ( [ "description = \"A Haskell " <> projectName <> " workspace generated by HWM(Haskell Workspace Manager)\";",
          "inputs = {",
          "  nixpkgs.url = \"github:NixOS/nixpkgs/" <> eraNixpkgs (selectEra (buildGHC benv)) <> "\";",
          "};",
          "outputs = { self, nixpkgs }:"
        ]
          <> letBlock
            ( [ "supportedSystems = [ \"x86_64-linux\" \"aarch64-linux\" \"x86_64-darwin\" \"aarch64-darwin\" ];",
                "forAllSystems = nixpkgs.lib.genAttrs supportedSystems;"
              ]
                <> generateOverlay ctxs
            )
            ( forAllSystems "packages" (generatePublicPackages ctx (buildPkgs benv))
                <> forAllSystems "devShells" (concatMap (uncurry generateDevShell) ctxs)
            )
            False
      )

braces :: [Text] -> [Text]
braces body =
  ["{"] <> map ("  " <>) body <> ["}"]

generatePublicPackages :: Context -> [Pkg] -> [Text]
generatePublicPackages _ [] = []
generatePublicPackages ctx@(projectName, _) pkgs = map renderPublicPackage pkgs <> renderDefaultPackage
  where
    renderPublicPackage pkg = format (pkgName pkg) <> " = " <> pkgsNixName ctx <> "." <> format (pkgName pkg) <> ";"
    renderDefaultPackage =
      let defaultPkg = maybeToList $ find ((projectName ==) . format . pkgName) pkgs
       in map (\pkg -> "default = " <> pkgsNixName ctx <> "." <> format (pkgName pkg) <> ";") defaultPkg

generateDevShell :: Name -> BuildEnvironment -> [Text]
generateDevShell _ BuildEnvironment {buildPkgs = []} = [] -- Handle empty workspace
generateDevShell projectName benv@BuildEnvironment {..} =
  [ "default = " <> pkgsNixName (projectName, benv) <> ".shellFor {",
    "  packages = p: [ " <> renderPackageList buildPkgs <> " ];",
    "  buildInputs = with " <> pkgsNixName (projectName, benv) <> "; ["
  ]
    <> map ("    " <>) libs
    <> [ "  ];",
         "};"
       ]
  where
    libs = ["cabal-install", "haskell-language-server", "hlint"] <> stackLibs
    stackLibs = ["stack" | buildStack]
    renderPackageList = T.intercalate " " . map (\pkg -> "p." <> format (pkgName pkg))

letBlock :: [Text] -> [Text] -> Bool -> [Text]
letBlock h body end =
  ["  let"]
    <> map ("    " <>) h
    <> [ "  in",
         "  {"
       ]
    <> map ("    " <>) body
    <> if end then ["  });"] else ["  };"]

forAllSystems :: Text -> [Text] -> [Text]
forAllSystems system body =
  [system <> " = forAllSystems (system:"]
    <> letBlock
      ["pkgs = import nixpkgs { inherit system; overlays = [ haskellOverlay ]; };"]
      body
      True
